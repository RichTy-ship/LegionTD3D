/**
 * Validates all static game configuration at startup and in unit tests.
 */
export function validateGameData(): { valid: boolean; errors: string[] } {
  const errors: string[] = [];

  // Check Fighter uniqueness and upgrade references
  const seenFighters = new Set<string>();
  for (const f of FIGHTERS) {
    if (seenFighters.has(f.id)) {
      errors.push(`Duplicate fighter ID: ${f.id}`);
    }
    seenFighters.add(f.id);
    if (f.cost <= 0 || f.hp <= 0 || f.attackDamage <= 0 || f.attackSpeed <= 0) {
      errors.push(`Invalid base stats on fighter: ${f.id}`);
    }
    if (!FACTIONS[f.faction]) {
      errors.push(`Unknown faction ${f.faction} on fighter ${f.id}`);
    }
    for (const upgId of f.upgradePaths) {
      if (!FIGHTER_MAP[upgId]) {
        errors.push(`Fighter ${f.id} references non-existent upgrade ${upgId}`);
      }
    }
  }

  // Check Mercenaries
  const seenMercs = new Set<string>();
  for (const m of MERCENARIES) {
    if (seenMercs.has(m.id)) {
      errors.push(`Duplicate mercenary ID: ${m.id}`);
    }
    seenMercs.add(m.id);
    if (m.mythiumCost <= 0 || m.hp <= 0 || m.damage <= 0) {
      errors.push(`Invalid stats on mercenary: ${m.id}`);
    }
  }

  // Check 21 Waves
  if (WAVES.length !== 21) {
    errors.push(`Expected 21 waves, found ${WAVES.length}`);
  }
  for (let i = 1; i <= 21; i++) {
    if (!WAVE_MAP[i]) {
      errors.push(`Missing wave number ${i}`);
    }
  }

  return {
    valid: errors.length === 0,
    errors,
  };
}
